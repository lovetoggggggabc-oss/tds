import assert from "node:assert/strict";
import vm from "node:vm";
import { readFile } from "node:fs/promises";
const js = await readFile("game.js", "utf8");
const html = await readFile("index.html", "utf8");
const css = await readFile("styles.css", "utf8");
assert.match(js, /Math\.floor\(reachedWave \/ 5\)/);
assert.deepEqual([4,5,10,20,40,100].map(w => Math.floor(w / 5)), [0,1,2,4,8,20]);
assert.match(js, /10: "kingSlime", 20: "timeRunner", 30: "meteor", 40: "galaxySlayer"/);
assert.match(js, /const summonedHp = Math\.max\(1, this\.hp \* \.5\)/);
assert.match(js, /speedBoostUntil = game\.gameTime \+ this\.abilityDuration/);
assert.match(js, /this\.damageBase\(20\)/);
assert.match(js, /forceDismantleRandom\(enemy\)/);
assert.match(js, /e\.type === "galaxySlayer" && !e\.bossRewardClaimed/);
assert.match(js, /STRIKE: "STRIKE"/); assert.match(js, /HORIZON: "HORIZON"/);
assert.match(js, /recipe: Object\.freeze\(\{ red: 1, white: 2, purple: 1 \}\), attackDamage: 725/);
assert.match(js, /recipe: Object\.freeze\(\{ green: 2, purple: 1 \}\)/);
assert.match(js, /target\.isBoss \? 2\.2 : \.85/);
assert.match(js, /1 \+ stacks \* \.0035/);
assert.match(js, /Math\.random\(\) < \.15/);
assert.equal((js.match(/id: CONSTELLATION_IDS\./g) || []).length, 11);
assert.match(html, /data-galaxy-fragments/); assert.match(html, /id="galaxyFragmentReward"/);
assert.match(css, /\.enemy\.kingSlime/); assert.match(css, /\.battle-result-overlay/); assert.match(css, /\.main-lobby/);
const prefix = js.slice(js.indexOf("const SCREEN_STATES"), js.indexOf("function performConstellationDraws"));
const saved = { starDust:0, starShards:0, meteorFragments:0, galaxyFragments:33, ownedStars:{}, ownedConstellations:["ASTROLOGER"], equippedConstellations:["ASTROLOGER"], oneTimeGrants:{starDust5000_v1:true,meteorFragments20_v2:true} };
const storage = new Map([["zodiacDefenseProgress", JSON.stringify(saved)]]);
const context = { Math, localStorage:{getItem:k=>storage.get(k),setItem:(k,v)=>storage.set(k,v)} }; vm.createContext(context);
vm.runInContext(`${prefix}\nthis.api={playerProgress,CONSTELLATION_LEVEL_COSTS,constellationLevelDamageMultiplier,constellationLevelAttackSpeedBonus,upgradeConstellation};`, context);
const { api } = context;
assert.equal(api.playerProgress.galaxyFragments,33); assert.deepEqual(JSON.parse(JSON.stringify(api.CONSTELLATION_LEVEL_COSTS)), {1:{copies:2,galaxyFragments:3},2:{copies:4,galaxyFragments:10},3:{copies:8,galaxyFragments:20}});
assert.deepEqual([1,2,3,4].map(api.constellationLevelDamageMultiplier),[1,1.5,2,2.5]);
assert.deepEqual([1,2,3,4].map(api.constellationLevelAttackSpeedBonus),[0,.5,1,1.5]);
console.log("Galactic update regression passed.");
