import assert from "node:assert/strict";
import vm from "node:vm";
import { readFile } from "node:fs/promises";

const file = await readFile("game.js", "utf8");
const prefix = file.slice(file.indexOf("const SCREEN_STATES"), file.indexOf("// Pointer Events"));
const saved = { starFragments: 0, meteorFragments: 120, ownedStars: {}, ownedConstellations: [], equippedConstellations: [], oneTimeGrants: { starFragments2000_v2: true } };
const storage = new Map([["zodiacDefenseProgress", JSON.stringify(saved)]]);
const context = { Math, localStorage: { getItem: (key) => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) } };
vm.createContext(context);
vm.runInContext(`${prefix}\nthis.api = { RELIC_DEFINITIONS, playerProgress, performRelicDraws, effectiveMaxStars };`, context);
const { RELIC_DEFINITIONS, playerProgress, performRelicDraws, effectiveMaxStars } = context.api;
assert.equal(Object.keys(RELIC_DEFINITIONS).length, 9, "exactly nine relics are registered");
assert.deepEqual(JSON.parse(JSON.stringify(playerProgress.ownedRelics)), [], "legacy saves migrate to an empty relic collection");
const one = performRelicDraws(1, () => 0);
assert.equal(one[0].id, "STEADFAST_HEART");
assert.equal(one[0].isNew, true);
assert.equal(playerProgress.meteorFragments, 110);
const duplicate = performRelicDraws(1, () => 0);
assert.equal(duplicate[0].isNew, false);
assert.equal(playerProgress.ownedRelics.filter((id) => id === "STEADFAST_HEART").length, 1, "duplicates are not persisted twice");
const sequence = Array.from({ length: 10 }, (_, index) => (index + .1) / 10);
const ten = performRelicDraws(10, () => sequence.shift());
assert.equal(ten.length, 10, "ten-draw performs ten independent selections");
assert.equal(playerProgress.meteorFragments, 0);
playerProgress.ownedRelics.push("GOOD_OF_BINDING_STAR");
assert.equal(effectiveMaxStars(), 22);
assert.match(file, /dawnKillProgress < 5/);
assert.doesNotMatch(file, /dawnKillProgress < 3/);
assert.match(file, /Math\.floor\(reachedWave \* 4 \* rewardMultiplier\)/);
assert.match(file, /Math\.floor\(Math\.floor\(reachedWave \/ 20\) \* rewardMultiplier\)/);
console.log("Relic regression passed: registry, migration, equal-pool draws, duplicate handling, costs, cap bonus, Dawn threshold, and reward flooring verified.");
