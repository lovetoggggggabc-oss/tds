import assert from "node:assert/strict";
import vm from "node:vm";
import { readFile } from "node:fs/promises";

const file = await readFile("game.js", "utf8");
const prefix = file.slice(file.indexOf("const SCREEN_STATES"), file.indexOf("// Pointer Events"));
const saved = { starFragments: 0, meteorFragments: 120, ownedStars: {}, ownedConstellations: [], equippedConstellations: [], oneTimeGrants: { starFragments2000_v2: true } };
const storage = new Map([["zodiacDefenseProgress", JSON.stringify(saved)]]);
const context = { Math, localStorage: { getItem: (key) => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) } };
vm.createContext(context);
vm.runInContext(`${prefix}\nthis.api = { RELIC_DEFINITIONS, RELIC_UPGRADE_COSTS, playerProgress, performRelicDraws, effectiveMaxStars, getRelicEffect, upgradeRelic };`, context);
const { RELIC_DEFINITIONS, RELIC_UPGRADE_COSTS, playerProgress, performRelicDraws, effectiveMaxStars, getRelicEffect, upgradeRelic } = context.api;
assert.equal(Object.keys(RELIC_DEFINITIONS).length, 13, "exactly thirteen relics are registered");
assert.deepEqual(JSON.parse(JSON.stringify(playerProgress.ownedRelics)), [], "legacy saves migrate to an empty relic collection");
const one = performRelicDraws(1, () => 0);
assert.equal(one[0].id, "STEADFAST_HEART");
assert.equal(one[0].isNew, true);
assert.equal(playerProgress.meteorFragments, 137);
const duplicate = performRelicDraws(1, () => 0);
assert.equal(duplicate[0].isNew, false);
assert.equal(playerProgress.ownedRelics.filter((id) => id === "STEADFAST_HEART").length, 1, "duplicates are not persisted twice");
assert.equal(playerProgress.relicProgress.STEADFAST_HEART.duplicates, 1, "duplicate is retained as upgrade material");
const sequence = Array.from({ length: 10 }, (_, index) => (index + .1) / 10);
const ten = performRelicDraws(10, () => sequence.shift());
assert.equal(ten.length, 10, "ten-draw performs ten independent selections");
assert.equal(playerProgress.meteorFragments, 104);
Object.assign(playerProgress.relicProgress.GOOD_OF_BINDING_STAR,{owned:true,level:4,duplicates:0});
assert.equal(effectiveMaxStars(), 25);
assert.deepEqual(JSON.parse(JSON.stringify(RELIC_UPGRADE_COSTS)), {1:{duplicates:3,starShards:200},2:{duplicates:6,starShards:400},3:{duplicates:10,starShards:1000}});
assert.deepEqual([1,2,3,4].map(level=>getRelicEffect("SONG_OF_STARS",level)),[.05,.06,.07,.08]);
Object.assign(playerProgress.relicProgress.STEADFAST_HEART,{owned:true,level:1,duplicates:3}); playerProgress.starShards=200;
assert.equal(upgradeRelic("STEADFAST_HEART"),true); assert.deepEqual(JSON.parse(JSON.stringify(playerProgress.relicProgress.STEADFAST_HEART)),{owned:true,level:2,duplicates:0}); assert.equal(playerProgress.starShards,0);
assert.match(file, /dawnKillProgress < 5/);
assert.doesNotMatch(file, /dawnKillProgress < 3/);
assert.match(file, /Math\.floor\(reachedWave \* 4 \* rewardMultiplier\)/);
assert.match(file, /Math\.floor\(reachedWave \/ 5\)/);
console.log("Relic regression passed: registry, migration, equal-pool draws, duplicate handling, costs, cap bonus, Dawn threshold, and reward flooring verified.");
