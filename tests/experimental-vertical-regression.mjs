import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const [js, css, html] = await Promise.all([readFile("game.js","utf8"),readFile("styles.css","utf8"),readFile("index.html","utf8")]);
assert.match(js, /EXPERIMENTAL_VERTICAL: "experimental_vertical"/);
assert.match(js, /const EXPERIMENTAL_WORLD_HEIGHT = 2\.8/);
assert.match(js, /id: "EXPERIMENTAL_NEBULA_ROUTE"/);
assert.match(js, /function worldToScreen\(point\)/);
assert.match(js, /function screenToWorld\(point\)/);
assert.match(js, /function clampCameraY\(value/);
assert.match(js, /function getViewportWorldBounds\(\)/);
assert.match(js, /manager\.cameraY = clampCameraY\(drag\.camera - delta\)/);
assert.match(js, /if \(drag\.moved\) \{ event\.preventDefault\(\); event\.stopImmediatePropagation\(\); \}/);
assert.match(js, /this\.cameraCleanup\?\.\(\)/);
assert.match(js, /this\.el\.style\.visibility = y < -100/);
assert.match(html, /id="play-experimental"/);
assert.match(html, /id="battleWorld"/);
assert.match(html, /id="experimentalMinimap"/);
assert.match(css, /\.arena\.experimental-vertical \.battle-world\{height:280%/);
assert.match(css, /\.experimental-minimap\{/);
assert.equal((html.match(/data-map-vote=/g)||[]).length,0, "normal vote cards remain generated only from the three normal map definitions");
console.log("Experimental vertical regression passed: isolated mode, 2.8x world, camera adapters, drag guard, culling, and minimap verified.");
