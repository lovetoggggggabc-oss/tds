import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const [js, css, html] = await Promise.all([readFile("game.js","utf8"),readFile("styles.css","utf8"),readFile("index.html","utf8")]);
assert.match(js, /this\.el\.style\.left = `\$\{this\.x\}%`/);
assert.match(js, /width: world\.clientWidth \|\| arena\.clientWidth/);
assert.doesNotMatch(js, /this\.el\.style\.transform = `translate3d/);
for (const id of ["DAWN","RADIANCE","SAGITTARIUS","ASTROLOGER","GUARDIAN","TWILIGHT","BOND","LINK","STRIKE","HORIZON"]) assert.match(js,new RegExp(`${id}: '<`));
for (const geometry of ["fourRay", "eightRay", "crossRay", "divineRay"]) assert.match(js,new RegExp(`const ${geometry}`));
assert.match(js, /viewBox="0 0 100 100" preserveAspectRatio="xMidYMid meet"/);
assert.match(js, /symmetricSparkles\(42, 2\.2\)/);
assert.match(css, /\.star\.stage-4\{--stage-scale:1\.1\}/);
assert.match(css, /\.star-node>\.star\{position:absolute;inset:0;transform-origin:50% 50%\}/);
assert.match(html, /<small>WAVE<\/small><span id="wave">0<\/span>/);
assert.match(css, /#wave[^}]+clamp\(30px,7\.2cqw,42px\)/);
console.log("Visual identity regression passed: centered symmetric four-stage SVGs, signatures, and wave hierarchy verified.");
